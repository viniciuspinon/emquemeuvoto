def baixar_foto_local(sq_candidato: str, source_url: str, nome: str, cor_hex: str = "#3B82F6") -> str:
    """
    Baixa a foto em alta qualidade e salva localmente em frontend/fotos/{sq_candidato}.jpg.
    """
    FOTOS_DIR.mkdir(parents=True, exist_ok=True)
    local_file = FOTOS_DIR / f"{sq_candidato}.jpg"

    if local_file.exists() and local_file.stat().st_size > 1000:
        return f"/static/fotos/{sq_candidato}.jpg"

    if source_url and source_url.startswith("http"):
        try:
            req = urllib.request.Request(
                source_url,
                headers={"User-Agent": "EmQuemEuVoto/1.0 (Mozilla/5.0)"}
            )
            with urllib.request.urlopen(req, timeout=10) as response:
                content = response.read()
                if len(content) > 1000:
                    with open(local_file, "wb") as f:
                        f.write(content)
                    print(f"  [Foto OK] {nome} -> {local_file.name} ({len(content)} bytes)")
                    return f"/static/fotos/{sq_candidato}.jpg"
        except Exception as e:
            print(f"  [Foto Erro para {nome}]: {e}")

    # Fallback gerando imagem visual limpa caso o link falhe
    try:
        from PIL import Image, ImageDraw
        img = Image.new("RGB", (260, 260), color="#121215")
        draw = ImageDraw.Draw(img)
        draw.rectangle([(0, 0), (259, 259)], outline=cor_hex, width=6)
        initials = "".join([p[0] for p in nome.split()[:2]]).upper()
        draw.ellipse([(65, 65), (195, 195)], fill="#1E1E24", outline=cor_hex, width=3)
        draw.text((130, 130), initials, fill="#FFFFFF", anchor="mm")
        img.save(local_file, "JPEG", quality=92)
        print(f"  [Foto Local Gerada] {nome} -> {local_file.name}")
    except Exception:
        pass

    return f"/static/fotos/{sq_candidato}.jpg"


